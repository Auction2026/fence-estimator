CREATE OR REPLACE VIEW v_estimate_margin_snapshot AS
SELECT
    e.id AS estimate_id,
    e.project_id,
    e.version,
    e.status,
    e.materials_total,
    e.labor_total,
    e.extras_total,
    e.subtotal,
    e.grand_total,
    e.markup_percent,
    ROUND(e.materials_total + e.labor_total + e.extras_total, 2) AS sell_before_tax,
    ROUND((e.materials_total + e.labor_total + e.extras_total) / NULLIF(1 + (e.markup_percent / 100.0), 0), 2) AS approximate_cost_basis,
    ROUND((e.materials_total + e.labor_total + e.extras_total) - ((e.materials_total + e.labor_total + e.extras_total) / NULLIF(1 + (e.markup_percent / 100.0), 0)), 2) AS implied_margin_value
FROM estimates e;

