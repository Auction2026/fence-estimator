CREATE OR REPLACE FUNCTION set_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION log_row_change()
RETURNS TRIGGER AS $$
DECLARE
    v_user_id BIGINT;
BEGIN
    BEGIN
        v_user_id := NULLIF(current_setting('app.current_user_id', true), '')::BIGINT;
    EXCEPTION WHEN OTHERS THEN
        v_user_id := NULL;
    END;

    IF TG_OP = 'INSERT' THEN
        INSERT INTO audit_log (table_name, record_id, action, old_values, new_values, user_id, created_at)
        VALUES (TG_TABLE_NAME, NEW.id, TG_OP, NULL, to_json(NEW), v_user_id, CURRENT_TIMESTAMP);
        RETURN NEW;
    ELSIF TG_OP = 'UPDATE' THEN
        INSERT INTO audit_log (table_name, record_id, action, old_values, new_values, user_id, created_at)
        VALUES (TG_TABLE_NAME, NEW.id, TG_OP, to_json(OLD), to_json(NEW), v_user_id, CURRENT_TIMESTAMP);
        RETURN NEW;
    ELSE
        INSERT INTO audit_log (table_name, record_id, action, old_values, new_values, user_id, created_at)
        VALUES (TG_TABLE_NAME, OLD.id, TG_OP, to_json(OLD), NULL, v_user_id, CURRENT_TIMESTAMP);
        RETURN OLD;
    END IF;
END;
$$ LANGUAGE plpgsql;

