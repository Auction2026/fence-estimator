CREATE OR REPLACE VIEW v_customer_lifetime_value AS
SELECT
    c.id AS customer_id,
    c.first_name,
    c.last_name,
    c.company,
    COUNT(DISTINCT p.id) AS project_count,
    COUNT(DISTINCT e.id) AS estimate_count,
    COALESCE(SUM(CASE WHEN e.status IN ('approved', 'converted') THEN e.grand_total ELSE 0 END), 0) AS approved_value,
    COALESCE(SUM(CASE WHEN ct.status IN ('signed', 'closed') THEN e.grand_total ELSE 0 END), 0) AS contracted_value,
    COALESCE(SUM(pm.amount), 0) AS payments_received
FROM customers c
LEFT JOIN projects p ON p.customer_id = c.id
LEFT JOIN estimates e ON e.project_id = p.id
LEFT JOIN contracts ct ON ct.estimate_id = e.id
LEFT JOIN payments pm ON pm.contract_id = ct.id
GROUP BY c.id;

CREATE OR REPLACE VIEW v_inventory_reorder AS
SELECT
    p.id,
    p.sku,
    p.name,
    p.category,
    p.stock_qty,
    p.unit,
    p.unit_price,
    p.cost_price,
    CASE
        WHEN p.category IN ('hardware', 'consumable', 'finish') THEN 50
        WHEN p.category LIKE 'chain-link%' THEN 20
        ELSE 10
    END AS reorder_point,
    CASE
        WHEN p.stock_qty <= 0 THEN 'out-of-stock'
        WHEN p.stock_qty <= 10 THEN 'critical'
        WHEN p.stock_qty <= 25 THEN 'watch'
        ELSE 'ok'
    END AS stock_status
FROM products p
WHERE p.active = TRUE;

