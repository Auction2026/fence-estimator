CREATE OR REPLACE VIEW v_estimate_pricing_summary AS
SELECT
    e.id AS estimate_id,
    e.project_id,
    p.name AS project_name,
    e.version,
    e.status,
    e.fence_type,
    e.fence_height,
    e.fence_color,
    e.linear_feet,
    e.post_count,
    e.materials_total,
    e.labor_total,
    e.extras_total,
    e.subtotal,
    e.tax_rate,
    e.tax_amount,
    e.grand_total,
    e.markup_percent,
    COALESCE(material_items.item_count, 0) AS material_item_count,
    COALESCE(gate_items.gate_count, 0) AS gate_count
FROM estimates e
JOIN projects p ON p.id = e.project_id
LEFT JOIN (
    SELECT estimate_id, COUNT(*) AS item_count
    FROM estimate_items
    WHERE category = 'material'
    GROUP BY estimate_id
) material_items ON material_items.estimate_id = e.id
LEFT JOIN (
    SELECT estimate_id, COUNT(*) AS gate_count
    FROM gates
    GROUP BY estimate_id
) gate_items ON gate_items.estimate_id = e.id;

